"""Write frontend/src/data/engineSites.json from the site catalogue and contract/precomputed/.

Usage (from the repository root): python backend/scripts/export_frontend_sites.py
Every number comes from the engine output (no hand-written values):
  elevation       : ground elevation at the site (LOLA, horizon_<id>.json)
  *VisibilityPct  : share of the precomputed year with the body centre above the terrain skyline
  max*Elevation   : highest elevation above the flat horizontal plane during that year
"""
import datetime as dt
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PRE = ROOT / "contract" / "precomputed"
index = json.load(open(PRE / "index.json", encoding="utf-8"))
t0, t1 = (dt.datetime.strptime(index[k], "%Y-%m-%dT%H:%M:%SZ") for k in ("startUtc", "endUtc"))
year_h = (t1 - t0).total_seconds() / 3600.0


def hours(win):
    f = lambda s: dt.datetime.strptime(s, "%Y-%m-%dT%H:%M:%SZ")
    return sum((f(w["endUtc"]) - f(w["startUtc"])).total_seconds() for w in win) / 3600.0


out = []
for s in index["sites"]:
    res = json.load(open(PRE / f"result_{s['id']}.json", encoding="utf-8"))
    hz = json.load(open(PRE / f"horizon_{s['id']}.json", encoding="utf-8"))
    out.append({"id": s["id"], "name": s["name"], "lat": s["latDeg"], "lon": s["lonDeg"],
                "elevation": round(hz["groundElevationM"]),
                "sunVisibilityPct": round(100 * hours(res["windows"]["sun"]) / year_h, 1),
                "earthVisibilityPct": round(100 * hours(res["windows"]["earth"]) / year_h, 1),
                "maxSolarElevation": round(max(res["sun"]["elevDeg"]), 2),
                "maxEarthElevation": round(max(res["earth"]["elevDeg"]), 2)})
meta = {"period": {"startUtc": index["startUtc"], "endUtc": index["endUtc"]},
        "note": "Generated by backend/scripts/export_frontend_sites.py from data/sites/sites.json and contract/precomputed/. Do not edit by hand.",
        "sites": out}
dest = ROOT / "frontend" / "src" / "data" / "engineSites.json"
json.dump(meta, open(dest, "w", encoding="utf-8"), indent=1, ensure_ascii=False)
print(f"{len(out)} sites -> {dest}")
for x in out:
    print(f"  {x['id']:26s} {x['elevation']:6d} m  Sun {x['sunVisibilityPct']:5.1f} %  Earth {x['earthVisibilityPct']:5.1f} %")
